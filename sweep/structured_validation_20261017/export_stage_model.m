function destination=export_stage_model
% Regenerate the self-contained user deliverable from frozen identified data.
out=fileparts(mfilename('fullpath'));root=fileparts(fileparts(out));
b=load(fullfile(root,'sweep','srivc_retest_20261016','model_z0.mat'));b=b.result;
q=load(fullfile(out,'trial_z0.mat'));q=q.result;
e=load(fullfile(out,'evaluation_z0.mat'));e=e.evaluation;
gdir=fullfile(root,'experiment_data','srivc_no_lrm_20261015','static_decoupling_20261016');
base=b.selected.fit;nm=numel(base.frequency_hz);omega=2*pi*base.frequency_hz;
c0=base.coefficients(1:2:2*nm,:);c1=base.coefficients(2:2:2*nm,:)./sqrt(base.a(:,2));
sc0=zeros(nm,16);sc1=zeros(nm,16);
assert(norm(abs(q.lambda)/(2*pi)-base.frequency_hz)<1e-9);
for m=1:nm
    residue=q.delay.residues(:,:,m);
    zeroth=-2*real(residue*conj(q.lambda(m)))/omega(m)^2;
    first=2*real(residue)/omega(m);
    sc0(m,:)=zeroth(:).';sc1(m,:)=first(:).';
end
replacements={ ...
    '__U0_RAW__',b.diagnostics.raw_mean_U.'; ...
    '__U0_CORRECTED__',b.diagnostics.mean_U.'; ...
    '__Y0__',b.diagnostics.mean_Y.'; ...
    '__FREQUENCIES__',base.frequency_hz; ...
    '__DAMPING__',base.damping; ...
    '__BASE_C0__',c0; '__BASE_C1__',c1; ...
    '__BASE_D__',reshape(base.coefficients(end,:),4,4); ...
    '__BASE_DELAY__',b.delay_matrix_seconds; ...
    '__STRUCT_C0__',sc0; '__STRUCT_C1__',sc1; ...
    '__STRUCT_D__',reshape(q.delay.direct,4,4); ...
    '__STRUCT_DELAY__',q.delay.delay_matrix_seconds; ...
    '__B_GEOMETRY__',readmatrix(fullfile(gdir,'source_B1.csv')); ...
    '__C_GEOMETRY__',readmatrix(fullfile(gdir,'source_C1.csv')); ...
    '__M_NOMINAL__',readmatrix(fullfile(gdir,'mass_inertia.csv')); ...
    '__TU_GEOMETRIC__',readmatrix(fullfile(root,'sweep','srivc_retest_20261016','geometric_Tu_full.csv')); ...
    '__TY_GEOMETRIC__',readmatrix(fullfile(root,'sweep','srivc_retest_20261016','geometric_Ty_full.csv')); ...
    '__NU_BAND__',e.band_static_nu; '__NY_BAND__',e.band_static_ny.'; ...
    '__NU_STRUCT__',e.nu; '__NY_STRUCT__',e.ny.'};
txt=fileread(fullfile(out,'stage_identified_z0_template.txt'));
for k=1:size(replacements,1),txt=strrep(txt,replacements{k,1},literal(replacements{k,2}));end
assert(isempty(regexp(txt,'__[A-Z0-9_]+__','once')),'Unresolved export placeholder.');
destination=fullfile(root,'stage_identified_z0.m');
fid=fopen(destination,'w','n','UTF-8');assert(fid>0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s',txt);fprintf('Exported %s (%d characters).\n',destination,numel(txt));
end
function txt=literal(A)
assert(isreal(A) && all(isfinite(A(:))));rows=cell(size(A,1),1);
for k=1:size(A,1),rows{k}=['    ' strtrim(sprintf('%.17g ',A(k,:)))];end
txt=['[' newline strjoin(rows,[';' newline]) newline ']'];
end
