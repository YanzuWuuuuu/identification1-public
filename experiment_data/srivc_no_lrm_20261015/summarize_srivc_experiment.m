function summarize_srivc_experiment
out=fileparts(mfilename('fullpath'));files=dir(fullfile(out,'srivc_z0*.mat'));rows={};
files=files(~endsWith({files.name},'_plot_checks.mat'));
for k=1:numel(files)
    S=load(fullfile(out,files(k).name),'result');r=S.result;h=r.fit.history;
    if ~isfield(r,'variant')
        r.variant=erase(files(k).name,{'srivc_z0','.mat'});
        if isempty(r.variant),r.variant='base';else,r.variant=r.variant(2:end);end
    end
    if ~isfield(r.fit,'fixed_modes'),r.fit.fixed_modes=[];end
    assert(all(diff(h(:,2))<=1e-12),'Nonmonotone accepted iteration.');
    assert(all(isfinite(r.fit.coefficients(:))));
    w=(r.validation.f/100).^2;
    err=norm((r.validation.Y-r.validation.prediction).*w,'fro')/norm(r.validation.Y.*w,'fro');
    assert(abs(err-r.validation.conditional_error)<1e-12);
    rows(end+1,:)={r.variant,r.fit.converged,r.fit.reason,r.fit.iterations, ...
        100*r.fit.relative_error,100*err,r.fit.score,numel(r.fit.frequency_hz), ...
        numel(r.fit.fixed_modes),r.training_frequency_step_hz}; %#ok<AGROW>
end
cases=cell2table(rows,'VariableNames',{'variant','converged','reason','iterations','training_error_percent', ...
    'conditional_validation_error_percent','score','components','fixed_components','training_step_hz'});
writetable(cases,fullfile(out,'variant_comparison.csv'));
P=load(fullfile(out,'srivc_z0_mid_fixed_full.mat'),'result');r=P.result;
A=load(fullfile(out,'srivc_z0_mid_fixed_full_shifted.mat'),'result');
L=load(fullfile(out,'srivc_z0_mid_fixed_full_low10.mat'),'result');
H=load(fullfile(out,'srivc_z0_mid_fixed_full_low20.mat'),'result');
T=load(fullfile(out,'synthetic_verification.mat'),'fit');
main=find(r.fit.frequency_hz>200);
meta=struct('primary_result','srivc_z0_mid_fixed_full.mat','input_data',r.source_file, ...
    'identification_input','Raw input and output DFT coefficients; no LRM; no FRF target', ...
    'algorithm','Additive frequency-domain SRIVC with X from measured partial output and Z from model partial output', ...
    'nonlinear_OE_refinement',false,'sampling_model','Continuous-frequency approximation to sampled DFT', ...
    'closed_loop_correction',false,'band_hz',[25 800], ...
    'training_error_percent',100*r.fit.relative_error, ...
    'conditional_validation_error_percent',100*r.validation.conditional_error, ...
    'validation_boundary_terms_refitted',true,'same_record_split',true, ...
    'iterations',r.fit.iterations,'score',r.fit.score,'converged',r.fit.converged, ...
    'fixed_background',struct('frequency_hz',15,'damping',.15,'estimated',false), ...
    'different_start_max_frequency_difference_hz',max(abs(r.fit.frequency_hz-A.result.fit.frequency_hz)), ...
    'background_10_to_20_max_target_frequency_difference_hz',max(abs(L.result.fit.frequency_hz(main)-H.result.fit.frequency_hz(main))), ...
    'synthetic_verification',T.fit.debug,'cases',table2struct(cases), ...
    'frf_plot_reference','Second-half Welch H1 FRF; not LRM; display and diagnostics only, not unbiased truth');
frfSummaryPath=fullfile(out,'srivc_z0_mid_fixed_full_frf_reference_summary.csv');
if isfile(frfSummaryPath)
    meta.frf_reference_comparison=table2struct(readtable(frfSummaryPath));
    meta.frf_error_definition='Unweighted Frobenius relative complex difference at the same frequencies; not raw-output prediction error or true-plant error';
end
fid=fopen(fullfile(out,'method_manifest.json'),'w');cl=onCleanup(@()fclose(fid));
fwrite(fid,jsonencode(meta,PrettyPrint=true),'char');clear cl;
disp(cases);fprintf('Background 10-20 Hz sensitivity for components above 200 Hz: %.9g Hz\n',meta.background_10_to_20_max_target_frequency_difference_hz);
end
